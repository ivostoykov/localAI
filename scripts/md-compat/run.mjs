// Generates REPORT.md and results.json for issue #18.
// Run from the repository root: node scripts/md-compat/run.mjs
// Requires the jsdom devDependency already present in the project.
// Turndown is fetched into .cache/ with a pinned hash check; it is not vendored.
//
// Generated data and manual grades are kept separate. Grades live in
// grades.mjs and are tied to the source hashes recorded there.

import fs from 'node:fs';
import path from 'node:path';
import { HERE, extractBody, render, loadTurndown, sourceInfo } from './harness.mjs';
import { extractionFixtures, rendererFixtures } from './fixtures.mjs';
import { gradedAgainst, extractionGrades, rendererGrades, turndownCompatGrades } from './grades.mjs';
import { runChecks } from './checks.mjs';

const fence = '~~~';
const block = (lang, text) => `${fence}${lang}\n${text}\n${fence}`;

const sources = sourceInfo();
const gradedMisses = Object.entries(gradedAgainst.sources)
  .filter(([file, hash]) => sources.hashes[file] !== hash)
  .map(([file]) => file);
const gradesStale = gradedMisses.length > 0;

const td = await loadTurndown();

const extraction = [];
for (const f of extractionFixtures) {
  const plain = td.plain(f.html);
  const gfm = td.gfm(f.html);
  const plainRender = await render(plain);
  const gfmRender = await render(gfm);
  extraction.push({
    ...f,
    current: extractBody(f.html),
    turndownPlain: plain,
    turndownGfm: gfm,
    turndownPlainRender: plainRender.summary,
    turndownGfmRender: gfmRender.summary
  });
}

const renderer = [];
for (const f of rendererFixtures) {
  const { summary, html } = await render(f.markdown);
  renderer.push({ ...f, rendered: summary, html });
}

const checks = runChecks({ extraction, renderer });

const tally = (values) => values.reduce((acc, value) => {
  acc[value] = (acc[value] || 0) + 1;
  return acc;
}, {});

const extractionCounts = tally(Object.values(extractionGrades).map(g => g.grade));
const rendererCounts = tally(Object.values(rendererGrades).map(g => g.grade));
const compatCounts = tally(Object.values(turndownCompatGrades).map(g => g.result));
const checksPassed = checks.filter(c => c.pass).length;

const md = [];
md.push('# Issue #18: Markdown conversion and rendering compatibility');
md.push('');
md.push('Generated by `node scripts/md-compat/run.mjs`. Regenerate rather than edit by hand.');
md.push('');
md.push('Scope: synthetic fixtures only. This is a compatibility inventory, not a measure of extraction or rendering accuracy on real pages, and not a model-quality evaluation.');
md.push('');
md.push('## Generated data and manual grades');
md.push('');
md.push('Two kinds of content appear below and are labelled separately:');
md.push('');
md.push('- Generated data: outputs and check results produced by this run from the fixtures.');
md.push('- Manual grades: a person\'s assessment of those outputs, stored in `grades.mjs` and tied to the source hashes below.');
md.push('');
md.push('## Assessed sources');
md.push('');
md.push(`- Assessed commit: \`${gradedAgainst.commit}\` (sources reviewed for the grades).`);
md.push(`- Generation: sources read from the working tree; the hashes below identify the exact content used.`);
md.push(`- CSS.escape: ${sources.cssEscape}.`);
md.push('');
md.push('| File | sha256 at run time | Matches graded hash |');
md.push('| --- | --- | --- |');
for (const [file, hash] of Object.entries(sources.hashes)) {
  const graded = gradedAgainst.sources[file];
  md.push(`| \`${file}\` | \`${hash}\` | ${graded === hash ? 'yes' : 'no'} |`);
}
md.push('');
if (gradesStale) {
  md.push(`> Warning: the manual grades are stale for ${gradedMisses.join(', ')}. Re-grade before relying on the counts.`);
} else {
  md.push('The source hashes match the recorded grades; the manual grades below apply to this run.');
}
md.push('');
md.push('## Pinned evaluation copies');
md.push('');
md.push(`- ${td.provenance.turndown.url}`);
md.push(`  - sha256 \`${td.provenance.turndown.sha256}\``);
md.push('- turndown-plugin-gfm 1.0.2');
md.push(`  - ${td.provenance.gfm.url}`);
md.push(`  - sha256 \`${td.provenance.gfm.sha256}\``);
md.push('');
md.push('## Method');
md.push('');
md.push('- `src/jslib/content-extractor.js` and `src/jslib/solomd2html.js` are loaded unmodified in jsdom (`scripts/md-compat/harness.mjs`).');
md.push('- `hasVisibleText()` and `getARIAContext()` are sliced out of `src/content.js` by function name and evaluated as-is, because `content.js` cannot be loaded on its own. No logic is copied.');
md.push('- jsdom has no `CSS.escape`, so the harness supplies a CSSOM-shaped polyfill for that one missing global. Checks P1 and P2 exercise the aria paths.');
md.push('- The extractor runs on a clone of `document.body` with `detectMainContent()` applied, then `extractEnhancedTextStructure()` and `formatEnhancedPageContent()`.');
md.push('- The renderer runs with `streamReply:false`, as in `tests/solomd2html.test.js`.');
md.push('- Turndown is an unmodified pinned evaluation copy, fetched on first run into `scripts/md-compat/.cache/` and hash-checked. It is not installed, vendored or shipped.');
md.push('');
md.push('## Classification');
md.push('');
md.push('- `bug`: valid input for the supported domain, wrong output.');
md.push('- `partial`: some content or structure is lost.');
md.push('- `unsupported`: input uses syntax outside the supported subset, or behaviour that may be intentional. No defect is claimed.');
md.push('- `pass`: output matches the input structure for the tested case.');
md.push('');
md.push('Counts are selected-fixture results from manual grading, not general accuracy.');
md.push('');
md.push(`- Automated checks: ${checksPassed} of ${checks.length} passed (generated, not a quality score).`);
md.push(`- Extraction grades: ${extractionCounts.pass || 0} pass, ${extractionCounts.partial || 0} partial, ${extractionCounts.bug || 0} bug, ${extractionCounts.unsupported || 0} unsupported of ${extraction.length}.`);
md.push(`- Renderer grades: ${rendererCounts.pass || 0} pass, ${rendererCounts.bug || 0} bug, ${rendererCounts.unsupported || 0} unsupported of ${renderer.length}.`);
md.push(`- Turndown output through the current renderer (manual grade): ${compatCounts.pass || 0} pass, ${compatCounts.fail || 0} fail of ${extraction.length}.`);
md.push('');
md.push('## Automated checks');
md.push('');
md.push('| Check | Expected | Actual | Result |');
md.push('| --- | --- | --- | --- |');
for (const c of checks) {
  md.push(`| ${c.id}: ${c.description} | ${c.expected.replace(/\|/g, '\\|')} | ${c.actual.replace(/\|/g, '\\|')} | ${c.pass ? 'pass' : 'fail'} |`);
}
md.push('');

md.push('## A. Extraction fixtures (HTML to Markdown for the model)');
md.push('');
md.push('All 15 labelled inputs, the generated outputs, and the manual grade for each.');
md.push('');
for (const r of extraction) {
  const grade = extractionGrades[r.id];
  md.push(`### ${r.id} — ${r.title}`);
  md.push('');
  md.push(`Generated input HTML:`);
  md.push('');
  md.push(block('html', r.html));
  md.push('');
  md.push('Generated current output:');
  md.push('');
  md.push(block('markdown', r.current));
  md.push('');
  md.push('Generated Turndown 7.2.4 (default):');
  md.push('');
  md.push(block('markdown', r.turndownPlain));
  md.push('');
  md.push('Generated Turndown 7.2.4 + gfm:');
  md.push('');
  md.push(block('markdown', r.turndownGfm));
  md.push('');
  md.push(`Manual grade: \`${grade.grade}\`. ${grade.note}`);
  md.push('');
}

md.push('## B. Renderer fixtures (model Markdown to HTML)');
md.push('');
for (const r of renderer) {
  const grade = rendererGrades[r.id];
  md.push(`### ${r.id} — ${r.title}`);
  md.push('');
  md.push('Generated input Markdown:');
  md.push('');
  md.push(block('markdown', r.markdown));
  md.push('');
  md.push('Generated rendered structure:');
  md.push('');
  md.push(block('text', r.rendered));
  md.push('');
  md.push(`Manual grade: \`${grade.grade}\`. ${grade.note}`);
  md.push('');
}

md.push('## C. Turndown output through the current renderer');
md.push('');
md.push('Diagnostic chain only; it does not occur in production. Grades are manual.');
md.push('');
md.push('| Fixture | Grade | Note |');
md.push('| --- | --- | --- |');
for (const r of extraction) {
  const compat = turndownCompatGrades[r.id];
  const note = compat.reason || compat.note || '';
  md.push(`| ${r.id} | ${compat.result} | ${note.replace(/\|/g, '\\|')} |`);
}
md.push('');
md.push('## Defects that are not syntax gaps');
md.push('');
md.push('- Absolute links are corrupted for valid Markdown: the `renderInline()` bare-URL rule (`solomd2html.js:433`) runs after the link rule (`:431`) and rewrites the href it just created. Relative links are unaffected. Fixtures R2, R9a; extraction fixture E14 for the same URL shape.');
md.push('- Nested lists and `pre > code` are duplicated by the extractor (`content-extractor.js:208-234`, `:332-356`); fixtures E2, E7, E15, confirmed by checks E2, E7, E15.');
md.push('- Document order is lost within a section (`content-extractor.js:473-521`); fixture E8, confirmed by check E8.');
md.push('- Ordered-list start is dropped (`content-extractor.js:388-402`); fixture E3, confirmed by check E3.');
md.push('');
md.push('## Limits');
md.push('');
md.push('- jsdom is not a browser. The defects recorded here are DOM-order and string-replacement facts, so layout independence is expected, but no browser run was made in this assessment.');
md.push('- No live page, no site-specific extractor and no model-answer quality was measured.');
md.push('- Header-less tables were checked against the gfm plugin only; a custom rule was not implemented.');
md.push('- The implementation-cost figure in the issue discussion is an estimate and has not been validated.');
md.push('- Grades are tied to the source hashes above; a run against different sources warns when they no longer match.');
md.push('');

fs.writeFileSync(path.join(HERE, 'REPORT.md'), md.join('\n'));
fs.writeFileSync(path.join(HERE, 'results.json'), JSON.stringify({
  assessed: {
    commit: gradedAgainst.commit,
    runCommit: sources.commit,
    sources: sources.hashes,
    gradedSources: gradedAgainst.sources,
    gradesStale,
    cssEscape: sources.cssEscape
  },
  pins: td.provenance,
  checks,
  grades: { extraction: extractionGrades, renderer: rendererGrades, turndownCompat: turndownCompatGrades },
  counts: { checks: { passed: checksPassed, total: checks.length }, extraction: extractionCounts, renderer: rendererCounts, turndownCompat: compatCounts },
  extraction,
  renderer
}, null, 2));

console.log(`Wrote REPORT.md and results.json (${extraction.length} extraction, ${renderer.length} renderer fixtures, ${checksPassed}/${checks.length} checks passed).`);
if (gradesStale) console.warn(`Manual grades are stale for: ${gradedMisses.join(', ')}`);
