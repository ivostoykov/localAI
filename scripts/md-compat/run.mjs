// Generates REPORT.md and results.json for issue #18.
// Run from the repository root: node scripts/md-compat/run.mjs
// Requires the jsdom devDependency already present in the project.
// Turndown is fetched into .cache/ with a pinned hash check; it is not vendored.

import fs from 'node:fs';
import path from 'node:path';
import { HERE, extractBody, render, loadTurndown } from './harness.mjs';
import { extractionFixtures, rendererFixtures } from './fixtures.mjs';

const fence = '~~~';

function block(lang, text) {
  return `${fence}${lang}\n${text}\n${fence}`;
}

// Renderer-side outcome of Turndown output, assessed per fixture.
// `pass` means the visible structure and inline meaning survive the current
// renderer. Failures name the renderer gap or the rule that adoption needs.
const turndownCompat = {
  E1: { result: 'pass' },
  E2: { result: 'pass' },
  E3: { result: 'pass' },
  E4: { result: 'fail', reason: 'renderer: one blockquote per line (R5)' },
  E5: { result: 'pass', note: 'gfm plugin only' },
  E6: { result: 'fail', reason: 'adoption rule: gfm emits raw HTML for a header-less table' },
  E7: { result: 'pass' },
  E8: { result: 'pass', note: 'gfm plugin only' },
  E9: { result: 'pass' },
  E10: { result: 'pass' },
  E11: { result: 'fail', reason: 'renderer: images unsupported (R10a)' },
  E12: { result: 'pass' },
  E13: { result: 'fail', reason: 'renderer: blockquote fragmentation and literal list text (R5)' },
  E14: { result: 'fail', reason: 'renderer: link corruption (R2, R9a)' },
  E15: { result: 'pass' }
};

const td = await loadTurndown();

const extractionResults = [];
for (const f of extractionFixtures) {
  const current = extractBody(f.html);
  const plain = td.plain(f.html);
  const gfm = td.gfm(f.html);
  const plainRender = await render(plain);
  const gfmRender = await render(gfm);
  extractionResults.push({
    ...f,
    current,
    turndownPlain: plain,
    turndownGfm: gfm,
    turndownPlainRender: plainRender.summary,
    turndownGfmRender: gfmRender.summary,
    turndownCompat: turndownCompat[f.id]
  });
}

const rendererResults = [];
for (const f of rendererFixtures) {
  const { summary, html } = await render(f.markdown);
  rendererResults.push({ ...f, rendered: summary, html });
}

const counts = (items, key = 'classification') => items.reduce((acc, item) => {
  acc[item[key]] = (acc[item[key]] || 0) + 1;
  return acc;
}, {});

const extractionCounts = counts(extractionResults);
const rendererCounts = counts(rendererResults);
const compatCounts = extractionResults.reduce((acc, r) => {
  acc[r.turndownCompat.result] = (acc[r.turndownCompat.result] || 0) + 1;
  return acc;
}, {});

const md = [];
md.push('# Issue #18: Markdown conversion and rendering compatibility');
md.push('');
md.push('Generated by `node scripts/md-compat/run.mjs`. Regenerate rather than edit by hand.');
md.push('');
md.push('Scope: synthetic fixtures only. This is a compatibility inventory, not a measure of extraction or rendering accuracy on real pages, and not a model-quality evaluation.');
md.push('');
md.push('## Method');
md.push('');
md.push('- `src/jslib/content-extractor.js` and `src/jslib/solomd2html.js` are loaded unmodified in jsdom (`scripts/md-compat/harness.mjs`).');
md.push('- `hasVisibleText()` and `getARIAContext()` are copied verbatim from `src/content.js` (`:388`, `:301`) because `content.js` cannot be loaded on its own; keep the copies in step.');
md.push('- The extractor runs on a clone of `document.body` with `detectMainContent()` applied, then `extractEnhancedTextStructure()` and `formatEnhancedPageContent()`.');
md.push('- The renderer runs with `streamReply:false`, as in `tests/solomd2html.test.js`.');
md.push('- Turndown is an unmodified pinned evaluation copy, fetched on first run into `scripts/md-compat/.cache/` and hash-checked. It is not vendored, installed or shipped.');
md.push('');
md.push('## Pinned evaluation copies');
md.push('');
md.push(`- ${td.provenance.turndown.url}`);
md.push(`  - sha256 \`${td.provenance.turndown.sha256}\``);
md.push('- turndown-plugin-gfm 1.0.2');
md.push(`  - ${td.provenance.gfm.url}`);
md.push(`  - sha256 \`${td.provenance.gfm.sha256}\``);
md.push('');
md.push('## Classification');
md.push('');
md.push('- `bug`: valid input for the supported domain, wrong output.');
md.push('- `partial`: some content or structure is lost.');
md.push('- `unsupported`: input uses syntax outside the supported subset, or uses behaviour that may be intentional. No defect is claimed.');
md.push('- `pass`: output matches the input structure for the tested case.');
md.push('');
md.push('Counts below are selected-fixture results, not general accuracy.');
md.push('');
md.push(`Extraction fixtures: ${extractionResults.length} total, ${extractionCounts.pass || 0} pass, ${extractionCounts.partial || 0} partial, ${extractionCounts.bug || 0} bug, ${extractionCounts.unsupported || 0} unsupported.`);
md.push('');
md.push(`Renderer fixtures: ${rendererResults.length} total, ${rendererCounts.pass || 0} pass, ${rendererCounts.bug || 0} bug, ${rendererCounts.unsupported || 0} unsupported, ${rendererCounts.partial || 0} partial.`);
md.push('');
md.push(`Extraction to display diagnostic chain, Turndown output through the current renderer: ${compatCounts.pass || 0} pass, ${compatCounts.fail || 0} fail of ${extractionResults.length}. The chain does not occur in production.`);
md.push('');

md.push('## A. Extraction fixtures (HTML to Markdown for the model)');
md.push('');
md.push('All 15 labelled inputs, the actual current output, and the pinned Turndown output.');
md.push('');
for (const r of extractionResults) {
  md.push(`### ${r.id} — ${r.title}`);
  md.push('');
  md.push(`Classification: \`${r.classification}\`. ${r.note}`);
  md.push('');
  md.push('Input HTML:');
  md.push('');
  md.push(block('html', r.html));
  md.push('');
  md.push('Current output:');
  md.push('');
  md.push(block('markdown', r.current));
  md.push('');
  md.push('Turndown 7.2.4 (default):');
  md.push('');
  md.push(block('markdown', r.turndownPlain));
  md.push('');
  md.push('Turndown 7.2.4 + gfm:');
  md.push('');
  md.push(block('markdown', r.turndownGfm));
  md.push('');
  md.push(`Turndown + gfm output through the current renderer: \`${r.turndownCompat.result}\`${r.turndownCompat.note ? ` (${r.turndownCompat.note})` : ''}${r.turndownCompat.reason ? ` — ${r.turndownCompat.reason}` : ''}.`);
  md.push('');
}

md.push('## B. Renderer fixtures (model Markdown to HTML)');
md.push('');
for (const r of rendererResults) {
  md.push(`### ${r.id} — ${r.title}`);
  md.push('');
  md.push(`Classification: \`${r.classification}\`. ${r.note}`);
  md.push('');
  md.push('Input Markdown:');
  md.push('');
  md.push(block('markdown', r.markdown));
  md.push('');
  md.push('Rendered structure:');
  md.push('');
  md.push(block('text', r.rendered));
  md.push('');
}

md.push('## Defects that are not syntax gaps');
md.push('');
md.push('- Absolute links are corrupted for valid Markdown: the `renderInline()` bare-URL rule (`solomd2html.js:433`) runs after the link rule (`:431`) and rewrites the href it just created. Relative links are unaffected. Fixtures R2, R9a; extraction fixture E14 for the same URL shape.');
md.push('- Nested lists and `pre > code` are duplicated by the extractor (`content-extractor.js:208-234`, `:332-356`); fixture E2, E7, E15.');
md.push('- Document order is lost within a section (`content-extractor.js:473-521`); fixture E8.');
md.push('- Ordered-list start is dropped (`content-extractor.js:388-402`); fixture E3.');
md.push('');
md.push('## Limits');
md.push('');
md.push('- jsdom is not a browser. The defects recorded here are DOM-order and string-replacement facts, so layout independence is expected, but no browser run was made in this assessment.');
md.push('- No live page, no site-specific extractor and no model-answer quality was measured.');
md.push('- Header-less tables were checked against the gfm plugin only; a custom rule was not implemented.');
md.push('- The implementation-cost figure in the issue discussion is an estimate and has not been validated.');
md.push('');

fs.writeFileSync(path.join(HERE, 'REPORT.md'), md.join('\n'));
fs.writeFileSync(path.join(HERE, 'results.json'), JSON.stringify({
  provenance: td.provenance,
  counts: { extraction: extractionCounts, renderer: rendererCounts, turndownCompat: compatCounts },
  extraction: extractionResults,
  renderer: rendererResults
}, null, 2));

console.log(`Wrote REPORT.md and results.json (${extractionResults.length} extraction, ${rendererResults.length} renderer fixtures).`);
